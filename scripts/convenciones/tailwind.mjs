const RE_PREFIJO = new RegExp(`^(?:${PREFIJOS.map((p) => p.replace(/[-]/g, "\\-")).join("|")})-.+`);

export function esUtilidad(token) {
  if (!token) return false;
  // Variantes: "hover:bg-x", "dark:invert", "md:flex", "[&>svg]:size-4".
  if (/^[^:]+:[^:]/.test(token)) return true;
  const base = token.replace(/^!/, "").replace(/^-/, "").replace(/!$/, "");
  if (base.includes("[") && base.includes("]")) return true;
  if (EXACTAS.has(base)) return true;
  // "p-4", "text-sm", "bg-zinc-50/80", "w-1/2".
  return RE_PREFIJO.test(base);
}

export function contieneUtilidades(texto) {
  return texto.split(/\s+/).some(esUtilidad);
}
